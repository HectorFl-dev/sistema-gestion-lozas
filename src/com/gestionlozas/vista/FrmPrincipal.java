    private void btnGuardarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarClienteActionPerformed
        String dni = txtDni.getText().trim();
String nom = txtNombre.getText().trim();
String ape = txtApellido.getText().trim();
String tel = txtTelefono.getText().trim();
String email = txtEmail.getText().trim();

if (!dni.matches("\\d{8}")) {
    JOptionPane.showMessageDialog(this, "El DNI debe tener exactamente 8 dígitos numéricos.", "Validación", JOptionPane.WARNING_MESSAGE);
    return;
}
if (nom.isEmpty() || ape.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Nombre y apellido son obligatorios.");
    return;
}

if (gestor.registrarCliente(dni, nom, ape, tel, email)) {
    JOptionPane.showMessageDialog(this, "Cliente guardado."); //guardado en el HashMap
    actualizarTablaClientes();
    limpiarClientes();
} else {
    JOptionPane.showMessageDialog(this, "El DNI ya se encuentra registrado.", "Error", JOptionPane.ERROR_MESSAGE);
}
// TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarClienteActionPerformed

