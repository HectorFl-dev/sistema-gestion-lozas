private void iniciarVista() {
    modeloClientes = new DefaultTableModel(new Object[]{"ID", "DNI", "Nombre", "Apellido", "Teléfono", "Email"}, 0);
    tblClientes.setModel(modeloClientes);

    modeloReservas = new DefaultTableModel(new Object[]{"ID", "Cliente", "Loza", "Fecha", "Horario", "Total", "Estado", "Método Pago"}, 0);
    tblReservas.setModel(modeloReservas);

    cboLozas.removeAllItems();
    for (LozaDeportiva l : gestor.listarLozas()) {
        cboLozas.addItem(l.getIdLoza() + " - " + l.getNombre());
    }

    paginadorClientes = new Paginador<>(gestor.listarClientes(), 5);
    actualizarTablaClientes();
    actualizarTablaReservas(gestor.getListaReservas());
}

private void actualizarTablaClientes() {
    paginadorClientes.actualizarDatos(gestor.listarClientes());
    modeloClientes.setRowCount(0);
    for (Cliente c : paginadorClientes.getPaginaActualDatos()) {
        modeloClientes.addRow(new Object[]{c.getIdCliente(), c.getDni(), c.getNombre(), c.getApellido(), c.getTelefono(), c.getEmail()});
    }
    lblPaginaCli.setText("Página " + paginadorClientes.getPaginaActual() + " de " + paginadorClientes.getTotalPaginas());
}

private void actualizarTablaReservas(List<Reserva> lista) {
    modeloReservas.setRowCount(0);
    for (Reserva r : lista) {
        modeloReservas.addRow(new Object[]{
            r.getIdReserva(),
            r.getCliente().getNombreCompleto(),
            r.getLoza().getNombre(),
            r.getFecha(),
            r.getHoraInicio() + " - " + r.getHoraFin(),
            "S/. " + r.getMontoTotal(),
            r.getEstado(),
            r.getPago().obtenerDetalleMetodo()
        });
    }
}

